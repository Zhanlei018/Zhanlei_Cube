// src/cube/moves.hpp —— 转动操作（函数）
//
// Move / Axis 这两个**类型**定义在 state.hpp 里（因为 State 需要它们的完整定义）。
// 本文件只放操作它们的函数。
//
// 设计目标：把"所有输入"归一化成同一个东西。
//
//   鼠标拖动  ┐
//   键盘按键  ├──▶  Move{axis, layer, dir, turns}  ──▶  applyMove(state, move)
//   随机打乱  │
//   逐步复原  ┘
//
// 只要这个归一化做好了，后面每个功能都只是"构造一个 Move 丢给 state"。
// 这就是为什么鼠标拖动那一层（阶段 4）会那么难，而这一层必须先用最简单。

#pragma once

#include <optional>
#include <string>
#include <vector>

#include "cube/state.hpp"

namespace cube {

// 层号：格坐标 -1 / 0 / 1 对应层 0 / 1 / 2（用 math.hpp 的 layerOf()）
using Layer = int;

// ---------------------------------------------------------------------------
// 转动 90°*turns
//
// ★ 这是整个逻辑层唯一的写入口。
//   动画播完之后，只调用它一次。渲染循环里绝不允许按当前动画角度改状态。
//
// 要做的事：
//   1. 取出这次要转的矩阵 R（用 math.hpp 的 rotX/rotY/rotZ，配合 axis）
//   2. 遍历所有 cubie，挑出 pos[axis] == layer - 1 的那些
//   3. 对它们做：
//          pos    = R * pos
//          orient = R * orient       ← 左乘！顺序反了颜色全乱
//
// ⚠️ C++ 细节：写 pos = R * pos 时，建议先算到临时变量再赋值，
//    别让 GLM 在同一个表达式里既读又写（别名问题）。
//
// ⚠️ 参数里的 turns / dir 都要用上：R 应该是 rot?(turns) 再乘上 dir 的影响。
//    想清楚 dir == -1 时该怎么办 —— 是取 R 的逆，还是把角度取负？
//    （提示：对 90° 的整数矩阵来说，逆矩阵 = 转置矩阵，但更简单的做法是
//      意识到"转 -90°"和"转 +270°"是一回事。）
// ---------------------------------------------------------------------------
void applyMove(State& state, const Move& move);

// 构造逆操作：轴和层不变，方向取反。
// 用途：逐步复原时，把历史记录反着做一遍就能回到初始状态。
Move inverseOf(const Move& move);

// ---------------------------------------------------------------------------
// 面记号 → Move
//
// 调试时用字符串输入最方便（"U R' F2"），界面上也要显示 "R'"。
// 内部一律用 axis/layer/dir，两套之间只有这一个转换函数，不要到处散落 if-else。
//
// 层号和方向的参考表（U = 上, D = 下, L = 左, R = 右, F = 前, B = 后）：
//
//     记号   轴   层        说明
//      U     Y    2        顶层，pos.y == +1
//      D     Y    0        底层，pos.y == -1
//      R     X    2        右层，pos.x == +1
//      L     X    0        左层，pos.x == -1
//      F     Z    2        前层，pos.z == +1
//      B     Z    0        后层，pos.z == -1
//
//   后缀 "'" 表示逆时针（取反 dir），后缀 "2" 表示 180°（turns = 2）。
//
// ⚠️ 关于"顺时针"：这里的 "R" 到底是绕 +X 转 +90° 还是 -90°？
//    这张表里 dir 的符号我故意没写死 —— 因为"顺时针"是**从外面看**定义的，
//    而 dir 说的是"绕正轴转"。两者的关系取决于右手坐标系，
//    你必须自己推一次、再用测试钉死。
//
//    推法：从 +X 方向（也就是右面外面）往原点看，此时 +Y 是"上"、+Z 是"前"。
//          "顺时针"意味着 上 → 前，也就是 +Y → +Z。
//          回想 rotX90 干的是不是这件事？如果不是，dir 就该取负。
//
// 解析失败返回 std::nullopt（不是抛异常，保持简单）。
// 支持的写法："U" "U'" "U2" "U'2"（大小写均可）
// ---------------------------------------------------------------------------
std::optional<Move> parseMove(const std::string& token);

// 把一串空格分隔的记号解析成动作序列："U R' F2"。
// 遇到无法解析的记号时，返回已经成功解析的部分（并可以让调用方打印警告）。
std::vector<Move> parseSequence(const std::string& text);
std::vector<Move> invertedSequence(const std::vector<Move>& moves);
}  // namespace cube
