// src/math/math.hpp —— 数学薄封装
//
// 这个文件是"契约"：它告诉别人有哪些函数、怎么调用。
// 具体实现写在 math.cpp 里。tools/math_check.cpp 会 include 这个头文件来验证。
//
// 注意：本文件禁止 include 任何 OpenGL / GLFW 头文件。
// 数学层要能脱离显卡独立运行 —— 这样你才能在没有窗口的情况下测试它。

#pragma once

// ⚠️ 踩过的坑：glm::imat3（整数矩阵）在 glm/ext/matrix_int3x3.hpp 里。
//    不在 glm/mat3x3.hpp（那个只给浮点的 glm::mat3），也不在 glm/matrix_int3x3.hpp。
//    报错长这样：'imat3' in namespace 'glm' does not name a type
//    —— 别以为是类型不存在，八成是头文件没 include 对。
#include <glm/ext/matrix_int3x3.hpp>
#include <glm/vec3.hpp>

namespace cube {

// ---------------------------------------------------------------------------
// 格坐标 → 层号
//
//   格坐标：-1, 0, 1   （原点在魔方中心）
//   层号：   0, 1, 2   （0 = 最靠近负方向那一层）
//
//   例：layerOf(-1) == 0, layerOf(0) == 1, layerOf(1) == 2
//
//   有了它，"这一层有哪些小方块"就变成一行判断：
//       cubie.pos[axis] == layer - 1
// ---------------------------------------------------------------------------
int layerOf(int coord);

// ---------------------------------------------------------------------------
// 轴字母 → 下标
//
//   'X' → 0,  'Y' → 1,  'Z' → 2
//   用于访问 glm::ivec3 的分量：pos[axisIndex('Y')] 就是 pos.y
// ---------------------------------------------------------------------------
int axisIndex(char axis);

// ---------------------------------------------------------------------------
// 整数旋转矩阵
//
//   参数 turns：转几个 90°。合法值 1 / 2 / 3（即 90° / 180° / 270°）
//   返回：3x3 整数矩阵，每个元素只可能是 0 或 ±1 —— 所以永远不会有浮点误差
//
//   右手定则：绕 +X 轴正向转 90°，+Y 会转到 +Z，+Z 会转到 -Y
//
//   怎么写出这个矩阵（别背）：
//     把三个单位向量分别转一下，看它们落到哪里，
//     再把这三个结果"按列"放进矩阵。
//
//   turns == 2 和 turns == 3 别硬编码三套矩阵，
//   让 turns == 1 的结果自己乘自己就行。
// ---------------------------------------------------------------------------
glm::imat3 rotX(int turns);
glm::imat3 rotY(int turns);
glm::imat3 rotZ(int turns);

}  // namespace cube
