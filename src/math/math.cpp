// 为什么 turns == 2 / 3 是"自己乘自己"，而不是再写两套矩阵？
//
//   因为手写 6 个矩阵 = 6 个出错机会，而且以后改一处忘一处。
//   连乘的写法只有一个可能出错的源头：rotX90() 本身。
//
//   这也是"矩阵乘法就是变换的复合"最直观的一次应用。
// ---------------------------------------------------------------------------
glm::imat3 rotX(int turns) {
    glm::imat3 result(1);                       // 单位阵 = 转 0 次
    const glm::imat3 quarter = rotX90();
    for (int i = 0; i < turns; ++i) {
        result = quarter * result;
    }
    return result;
}

